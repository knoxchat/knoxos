#!/usr/bin/env bash
# Generate KnoxOS Secure Boot keys (PK / KEK / db) and optionally enroll
# them into an OVMF vars store for QEMU.
#
# Always writes PEM + DER under dist/sbkeys/. Enrollment into OVMF_VARS
# runs when `virt-fw-vars` (python3-virt-firmware) is on PATH.
#
# Usage:
#   ./scripts/secure-boot-enroll.sh
#   OVMF_CODE=... OVMF_VARS=... ./scripts/secure-boot-enroll.sh
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="${SBKEYS_OUT:-$ROOT/dist/sbkeys}"
mkdir -p "$OUT"

need_openssl() {
  if ! command -v openssl >/dev/null 2>&1; then
    echo "openssl is required to generate PK/KEK/db" >&2
    exit 1
  fi
}

make_key() {
  local name="$1"
  local cn="$2"
  if [ -f "$OUT/${name}.key" ] && [ -f "$OUT/${name}.crt" ]; then
    echo "keep $OUT/${name}.key"
    return
  fi
  openssl req -new -x509 -newkey rsa:2048 -nodes -days 3650 \
    -subj "/CN=KnoxOS ${cn}/" \
    -keyout "$OUT/${name}.key" \
    -out "$OUT/${name}.crt" >/dev/null 2>&1
  openssl x509 -in "$OUT/${name}.crt" -outform DER -out "$OUT/${name}.cer"
  echo "wrote $OUT/${name}.key + .crt + .cer"
}

need_openssl
make_key pk "Platform Key"
make_key kek "Key Exchange Key"
make_key db "Signature Database"

cat > "$OUT/README.md" <<'EOF'
# KnoxOS Secure Boot keys

Generated by `scripts/secure-boot-enroll.sh`.

| File | Role |
|------|------|
| `pk.key` / `pk.crt` / `pk.cer` | Platform Key (PK) |
| `kek.key` / `kek.crt` / `kek.cer` | Key Exchange Key (KEK) |
| `db.key` / `db.crt` / `db.cer` | Signature database (db) |

## Enroll into OVMF (QEMU)

If `virt-fw-vars` is installed (`pip install virt-firmware` or
`apt install python3-virt-firmware`):

```
./scripts/secure-boot-enroll.sh
```

writes `OVMF_VARS.knoxos.fd` next to these keys. Boot with:

```
qemu-system-x86_64 \
  -drive if=pflash,format=raw,readonly=on,file=$OVMF_CODE \
  -drive if=pflash,format=raw,file=dist/sbkeys/OVMF_VARS.knoxos.fd \
  ...
```

Sign `BOOTX64.EFI` extracted from the GPT (not the disk image) with
`sbsign --key db.key --cert db.crt`. `scripts/qemu-secure-boot.sh` does
that and boots OVMF with `smm=on`. TPM measured boot is a later gate.
EOF

# virt-fw-vars --set-pk takes a UUID, not a display name.
SB_OWNER="${SB_OWNER:-4b6e6f78-4f53-11ef-9b0a-6b6e6f786f73}"

enroll_ovmf() {
  if ! command -v virt-fw-vars >/dev/null 2>&1; then
    echo "virt-fw-vars not found; keys are in $OUT (enroll later with python3-virt-firmware)"
    echo "GATE_SB keys generated"
    return 0
  fi

  local vars=""
  # Prefer 4M templates: Ubuntu 24.04 dropped the 2M OVMF_VARS.fd, and
  # qemu-secure-boot.sh pairs 4M secboot CODE with 4M VARS.
  local candidates=(
    "${OVMF_VARS:-}"
    "/usr/share/OVMF/OVMF_VARS_4M.fd"
    "/usr/share/edk2/ovmf/OVMF_VARS_4M.fd"
    "/usr/share/edk2-ovmf/x64/OVMF_VARS_4M.fd"
    "/usr/share/OVMF/OVMF_VARS.fd"
    "/usr/share/edk2/ovmf/OVMF_VARS.fd"
    "/usr/share/edk2-ovmf/x64/OVMF_VARS.fd"
    "/opt/homebrew/share/qemu/edk2-i386-vars.fd"
    "/usr/local/share/qemu/edk2-i386-vars.fd"
  )
  local c
  for c in "${candidates[@]}"; do
    [ -n "$c" ] && [ -f "$c" ] && vars="$c" && break
  done
  if [ -z "$vars" ]; then
    echo "no OVMF_VARS.fd found; keys are in $OUT"
    echo "GATE_SB keys generated"
    return 0
  fi

  virt-fw-vars \
    --input "$vars" \
    --output "$OUT/OVMF_VARS.knoxos.fd" \
    --secure-boot \
    --set-pk "$SB_OWNER" "$OUT/pk.crt" \
    --add-kek "$SB_OWNER" "$OUT/kek.crt" \
    --add-db "$SB_OWNER" "$OUT/db.crt"
  echo "enrolled PK/KEK/db into $OUT/OVMF_VARS.knoxos.fd (from $vars)"
  echo "GATE_SB ovmf pk"
}

enroll_ovmf
