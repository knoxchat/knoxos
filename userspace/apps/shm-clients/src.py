    a.js("fail")
    a.emit(0x49, 0x89, 0xC5)
    a.emit(0x41, 0xC7, 0x45, 0x00)
    a.emit_u32(magic)
    a.emit(0x41, 0xC7, 0x45, 0x04)
    a.emit_u32(width)
