def _wayland_protocol_blob() -> tuple[bytes, int]:
    buf = bytearray()

    def hdr(obj: int, opcode: int, size: int) -> None:
        buf.extend(obj.to_bytes(4, "little"))
        buf.extend(opcode.to_bytes(2, "little"))
        buf.extend(size.to_bytes(2, "little"))

    def put_str(dst: bytearray, s: str) -> None:
        n = len(s) + 1
        dst.extend(n.to_bytes(4, "little"))
        dst.extend(s.encode())
        dst.append(0)
        while len(dst) % 4 != 0:
            dst.append(0)

    hdr(1, 1, 12)
    buf.extend((2).to_bytes(4, "little"))
    args = bytearray()
    args.extend((1).to_bytes(4, "little"))
    put_str(args, "wl_compositor")
    args.extend((4).to_bytes(4, "little"))
    args.extend((3).to_bytes(4, "little"))
    hdr(2, 0, 8 + len(args))
    buf.extend(args)
    args = bytearray()
    args.extend((2).to_bytes(4, "little"))
    put_str(args, "wl_shm")
    args.extend((1).to_bytes(4, "little"))
    args.extend((4).to_bytes(4, "little"))
    hdr(2, 0, 8 + len(args))
    buf.extend(args)
    hdr(4, 0, 24)
    buf.extend((5).to_bytes(4, "little"))
    buf.extend((0x4000).to_bytes(4, "little"))
    vaddr_off = len(buf)
    buf.extend((0).to_bytes(8, "little"))
    hdr(5, 0, 32)
    buf.extend((6).to_bytes(4, "little"))
    buf.extend((0).to_bytes(4, "little"))
    buf.extend((64).to_bytes(4, "little"))
    buf.extend((64).to_bytes(4, "little"))
    buf.extend((256).to_bytes(4, "little"))
    buf.extend((0).to_bytes(4, "little"))
    hdr(3, 0, 12)
    buf.extend((7).to_bytes(4, "little"))
    hdr(7, 1, 20)
    buf.extend((6).to_bytes(4, "little"))
    buf.extend((0).to_bytes(4, "little"))
    buf.extend((0).to_bytes(4, "little"))
    hdr(7, 6, 8)
    return bytes(buf), vaddr_off


