def gpui_shm_unix_elf(magic: int, width: int, height: int, marker: bytes) -> bytes:
    byte_count = width * height * 4
    mmap_len = max((byte_count + 0xFFF) & ~0xFFF, 0x4000)
    a = Reloc()
    a.emit(0x48, 0xC7, 0xC0, 0x09, 0x00, 0x00, 0x00)
    a.emit(0x48, 0x31, 0xFF)
    a.emit(0x48, 0xC7, 0xC6)
    a.emit_u32(mmap_len)
    a.emit(0x48, 0xC7, 0xC2, 0x03, 0x00, 0x00, 0x00)
    a.emit(0x49, 0xC7, 0xC2, 0x22, 0x80, 0x00, 0x00)
    a.emit(0x49, 0xC7, 0xC0, 0xFF, 0xFF, 0xFF, 0xFF)
    a.emit(0x4D, 0x31, 0xC9)
    a.emit(0x0F, 0x05)
