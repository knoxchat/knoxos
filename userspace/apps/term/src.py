"""Ring 3 openpty + SHM present (GATE_TERM)."""

from elfpack import Reloc, build_static_user_elf


def elf() -> bytes:
    marker = b"GATE_TERM pty userspace\n"
    interactive = b"GATE_TERM pty interactive\n"
    fill = (0xFF2B_1A0D).to_bytes(4, "little")
    a = Reloc()

    # mmap(NULL, 0x4000, PROT_READ|PROT_WRITE, MAP_PRIVATE|MAP_ANONYMOUS, -1, 0)
    a.emit(0x48, 0xC7, 0xC0, 0x09, 0x00, 0x00, 0x00)
    a.emit(0x48, 0x31, 0xFF)
    a.emit(0x48, 0xC7, 0xC6, 0x00, 0x40, 0x00, 0x00)
    a.emit(0x48, 0xC7, 0xC2, 0x03, 0x00, 0x00, 0x00)
    a.emit(0x49, 0xC7, 0xC2, 0x22, 0x80, 0x00, 0x00)
    a.emit(0x49, 0xC7, 0xC0, 0xFF, 0xFF, 0xFF, 0xFF)
    a.emit(0x4D, 0x31, 0xC9)
    a.emit(0x0F, 0x05)
    a.emit(0x48, 0x85, 0xC0)
    a.js("fail")
    a.emit(0x49, 0x89, 0xC4)
    a.emit(0x4C, 0x89, 0xE7)
    a.emit(0x48, 0xC7, 0xC1, 0x00, 0x10, 0x00, 0x00)
    a.emit(0xB8, fill[0], fill[1], fill[2], fill[3])
    a.emit(0xF3, 0xAB)

    # openpty(&master, &name)  syscall 0x3051
    a.emit(0x48, 0x81, 0xEC, 0x80, 0x00, 0x00, 0x00)
    a.emit(0x48, 0xC7, 0xC0, 0x51, 0x30, 0x00, 0x00)
    a.emit(0x48, 0x89, 0xE7)
    a.emit(0x48, 0x8D, 0x74, 0x24, 0x08)
    a.emit(0x0F, 0x05)
    a.emit(0x48, 0x85, 0xC0)
    a.js("fail")

    # open(slave_name, O_RDWR)
    a.emit(0x48, 0xC7, 0xC0, 0x02, 0x00, 0x00, 0x00)
    a.emit(0x48, 0x8D, 0x7C, 0x24, 0x08)
    a.emit(0x48, 0xC7, 0xC6, 0x02, 0x00, 0x00, 0x00)
    a.emit(0x48, 0x31, 0xD2)
    a.emit(0x0F, 0x05)
    a.emit(0x48, 0x85, 0xC0)
    a.js("fail")
    a.emit(0x49, 0x89, 0xC6)

    # write(slave, "ok\\n", 3)
    a.emit(0x48, 0xC7, 0xC0, 0x01, 0x00, 0x00, 0x00)
    a.emit(0x4C, 0x89, 0xF7)
    a.lea_rsi("echo")
    a.emit(0x48, 0xC7, 0xC2, 0x03, 0x00, 0x00, 0x00)
    a.emit(0x0F, 0x05)
    a.emit(0x48, 0x85, 0xC0)
    a.js("fail")

    # read(master, [rsp+0x40], 8)
    a.emit(0x48, 0xC7, 0xC0, 0x00, 0x00, 0x00, 0x00)
    a.emit(0x48, 0x63, 0x3C, 0x24)
    a.emit(0x48, 0x8D, 0x74, 0x24, 0x40)
    a.emit(0x48, 0xC7, 0xC2, 0x08, 0x00, 0x00, 0x00)
    a.emit(0x0F, 0x05)
    a.emit(0x48, 0x85, 0xC0)
    a.jle("fail")

    # open("/dev/wl0", O_RDWR)
    a.emit(0x48, 0xC7, 0xC0, 0x02, 0x00, 0x00, 0x00)
    a.lea_rdi("path")
    a.emit(0x48, 0xC7, 0xC6, 0x02, 0x00, 0x00, 0x00)
    a.emit(0x48, 0x31, 0xD2)
    a.emit(0x0F, 0x05)
    a.emit(0x48, 0x85, 0xC0)
    a.js("fail")
    a.emit(0x49, 0x89, 0xC5)

    # ioctl(fd, 0x574C0001, buf)
    a.emit(0x48, 0xC7, 0xC0, 0x10, 0x00, 0x00, 0x00)
    a.emit(0x4C, 0x89, 0xEF)
    a.emit(0x48, 0xC7, 0xC6, 0x01, 0x00, 0x4C, 0x57)
    a.emit(0x4C, 0x89, 0xE2)
    a.emit(0x0F, 0x05)
    a.emit(0x48, 0x85, 0xC0)
    a.js("fail")

    a.emit(0x48, 0xC7, 0xC0, 0x01, 0x00, 0x00, 0x00)
    a.emit(0x48, 0xC7, 0xC7, 0x01, 0x00, 0x00, 0x00)
    a.lea_rsi("marker")
    a.emit(0x48, 0xC7, 0xC2)
    a.emit_u32(len(marker))
    a.emit(0x0F, 0x05)
    a.emit(0x48, 0xC7, 0xC0, 0x01, 0x00, 0x00, 0x00)
    a.emit(0x48, 0xC7, 0xC7, 0x01, 0x00, 0x00, 0x00)
    a.lea_rsi("interactive")
    a.emit(0x48, 0xC7, 0xC2)
    a.emit_u32(len(interactive))
    a.emit(0x0F, 0x05)
    a.emit(0x48, 0x31, 0xFF)
    a.emit(0xEB, 0x07)
    a.label("fail")
    a.emit(0x48, 0xC7, 0xC7, 0x01, 0x00, 0x00, 0x00)
    a.emit(0x48, 0xC7, 0xC0, 0x3C, 0x00, 0x00, 0x00)
    a.emit(0x0F, 0x05)
    a.label("path")
    a.emit(*b"/dev/wl0\0")
    a.label("marker")
    a.emit(*marker)
    a.label("interactive")
    a.emit(*interactive)
    a.label("echo")
    a.emit(*b"ok\n")
    return build_static_user_elf(a.finish())
