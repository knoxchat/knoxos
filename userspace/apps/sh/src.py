"""Ring 3 /bin/sh: prompt, read, ShellExecute syscall."""

from elfpack import Reloc, build_static_user_elf


def elf() -> bytes:
    a = Reloc()
    a.emit(0x48, 0x81, 0xEC, 0x00, 0x01, 0x00, 0x00)  # sub rsp, 0x100
    a.label("loop")
    # write(1, "$ ", 2)
    a.emit(0x48, 0xC7, 0xC0, 0x01, 0x00, 0x00, 0x00)
    a.emit(0x48, 0xC7, 0xC7, 0x01, 0x00, 0x00, 0x00)
    a.lea_rsi("prompt")
    a.emit(0x48, 0xC7, 0xC2, 0x02, 0x00, 0x00, 0x00)
    a.emit(0x0F, 0x05)

    # read(0, rsp, 255)
    a.emit(0x48, 0xC7, 0xC0, 0x00, 0x00, 0x00, 0x00)
    a.emit(0x48, 0x31, 0xFF)
    a.emit(0x48, 0x89, 0xE6)
    a.emit(0x48, 0xC7, 0xC2, 0xFF, 0x00, 0x00, 0x00)
    a.emit(0x0F, 0x05)
    a.emit(0x48, 0x85, 0xC0)
    a.jle("exit")

    # r8 = n; rsi = buf; strip trailing \n / \r
    a.emit(0x49, 0x89, 0xC0)
    a.emit(0x48, 0x89, 0xE6)
    a.emit(0x4C, 0x89, 0xC1)  # rcx = n
    a.emit(0x48, 0xFF, 0xC9)  # dec rcx
    a.emit(0x80, 0x3C, 0x0E, 0x0A)  # cmp byte [rsi+rcx], '\n'
    a.jne("check_cr")
    a.emit(0x49, 0xFF, 0xC8)  # dec r8
    a.jmp("go")
    a.label("check_cr")
    a.emit(0x80, 0x3C, 0x0E, 0x0D)
    a.jne("go")
    a.emit(0x49, 0xFF, 0xC8)

    a.label("go")
    # ShellExecute(buf, n)  syscall 0x3053
    a.emit(0x48, 0x89, 0xF7)  # rdi = buf
    a.emit(0x4C, 0x89, 0xC6)  # rsi = n
    a.emit(0x48, 0xC7, 0xC0, 0x53, 0x30, 0x00, 0x00)
    a.emit(0x0F, 0x05)
    a.jmp("loop")

    a.label("exit")
    a.emit(0x48, 0xC7, 0xC0, 0x3C, 0x00, 0x00, 0x00)
    a.emit(0x48, 0x31, 0xFF)
    a.emit(0x0F, 0x05)
    a.label("prompt")
    a.emit(*b"$ ")
    return build_static_user_elf(a.finish())
