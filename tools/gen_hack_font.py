def char_label(code):
    ch = chr(code)
    if ch == '\\':
        return "0x{:02X} '{}'".format(code, "\\\\")
    elif ch == '\'':
        return "0x{:02X} '\\''".format(code)
    else:
        return "0x{:02X} '{}'".format(code, ch)


def format_row(rows, per_line=8):
    parts = []
    for i in range(0, len(rows), per_line):
        chunk = rows[i:i+per_line]
        parts.append(", ".join("0x{:02X}".format(b) for b in chunk))
    return ",\n     ".join(parts)


