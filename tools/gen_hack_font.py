OUTPUT_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "kernel", "src", "gui", "hack_font.rs")

FIRST_CHAR = 0x20
LAST_CHAR = 0x7E
GLYPH_COUNT = LAST_CHAR - FIRST_CHAR + 1

# ── 8x16 rasterization from TTF ─────────────────────────────────────────

def rasterize_8x16(ttf_path):
    """Rasterize all printable ASCII as 8x16 bitmaps from Hack TTF."""
    font = ImageFont.truetype(ttf_path, 12)
    asc, desc = font.getmetrics()
    total = asc + desc  # should be ~15, fits in 16
    
    glyphs = []
    for code in range(FIRST_CHAR, LAST_CHAR + 1):
        ch = chr(code)
        img = Image.new('L', (8, 16), 0)
        draw = ImageDraw.Draw(img)
        
        if ch != ' ':
            bbox = font.getbbox(ch)
            gw = bbox[2] - bbox[0]
            x_pos = (8 - gw) // 2 - bbox[0]
            baseline_y = (16 - total) // 2 + asc
            y_pos = baseline_y - asc
            draw.text((x_pos, y_pos), ch, fill=255, font=font)
        
        rows = []
        for y in range(16):
            byte_val = 0
            for x in range(8):
                p = img.getpixel((x, y))
                if p > 80:
                    byte_val |= (1 << (7 - x))
            rows.append(byte_val)
        glyphs.append((code, rows))
    
    return glyphs

