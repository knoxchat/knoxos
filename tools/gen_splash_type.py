#!/usr/bin/env python3
"""Rasterize KnoxOS splash / login wordmark strings from Inter TTFs.

FreeType AA (via Pillow) is used so the boot splash does not depend on the
in-kernel TrueType rasterizer for display-sized type. Output is packed
alpha bitmaps consumed by kernel/src/gui/splash_type.rs.
"""

from __future__ import annotations

import os
import struct
import sys

from PIL import Image, ImageDraw, ImageFont

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(SCRIPT_DIR, "..")
FONT_DIR = os.path.join(ROOT, "kernel", "fonts")
OUT_DIR = os.path.join(ROOT, "kernel", "fonts", "splash")
PREVIEW_PATH = os.path.join(ROOT, "tools", "splash_type_preview.png")
RS_PATH = os.path.join(ROOT, "kernel", "src", "gui", "splash_type.rs")

INTER_BOLD = os.path.join(FONT_DIR, "Inter-Bold.ttf")
INTER_REGULAR = os.path.join(FONT_DIR, "Inter-Regular.ttf")

STRINGS = [
    # name, text, ttf, px, tracking
    ("logo", "KnoxOS", INTER_BOLD, 80, 1),
    ("tagline", "SI-native Operating System", INTER_REGULAR, 20, 3),
    ("version", "v0.2.4", INTER_REGULAR, 14, 0),
    ("status", "Initializing...", INTER_REGULAR, 14, 1),
    ("login_title", "KnoxOS", INTER_BOLD, 36, 0),
    ("login_sub", "Welcome back", INTER_REGULAR, 16, 0),
    ("menu_title", "KnoxOS Boot Menu", INTER_BOLD, 36, 1),
]


def render_string_v2(ttf: str, text: str, px: int, tracking: int) -> Image.Image:
    """Render with FreeType AA at native size (no supersample) plus tracking."""
    font = ImageFont.truetype(ttf, px)
    # Measure
    xs = []
    pen = 0
    min_y = 0
    max_y = 0
    max_x = 0
    for i, ch in enumerate(text):
        bbox = font.getbbox(ch)
        if bbox is None:
            adv = int(round(font.getlength(ch) or px * 0.3))
            xs.append((pen, 0, 0, 0, 0, ch))
            pen += adv
            if i + 1 < len(text) and ch != " " and text[i + 1] != " ":
                pen += tracking
            continue
        x0, y0, x1, y1 = bbox
        xs.append((pen, x0, y0, x1, y1, ch))
        min_y = min(min_y, y0)
        max_y = max(max_y, y1)
        max_x = max(max_x, pen + x1)
        pen += int(round(font.getlength(ch)))
        if i + 1 < len(text) and ch != " " and text[i + 1] != " ":
            pen += tracking

    pad = 2
    w = max(1, max_x + pad * 2)
    h = max(1, (max_y - min_y) + pad * 2)
    img = Image.new("L", (w, h), 0)
    draw = ImageDraw.Draw(img)
    for pen_x, x0, y0, x1, y1, ch in xs:
        draw.text((pad + pen_x, pad - min_y), ch, font=font, fill=255)
    crop = img.getbbox()
    if crop:
        img = img.crop(crop)
    return img


def write_bin(path: str, img: Image.Image) -> None:
    w, h = img.size
    data = img.tobytes()
    with open(path, "wb") as f:
        f.write(struct.pack("<HH", w, h))
        f.write(data)


def write_rust(entries: list[tuple[str, Image.Image]]) -> None:
    lines = [
        "//! Pre-rasterized Inter splash / login type (generated by tools/gen_splash_type.py)",
        "//!",
        "//! Packed little-endian header: width:u16, height:u16, then width*height alpha bytes.",
        "",
        "#[derive(Clone, Copy)]",
        "pub struct SplashBitmap {",
        "    pub width: u16,",
        "    pub height: u16,",
        "    pub pixels: &'static [u8],",
        "}",
        "",
        "const fn parse(raw: &'static [u8]) -> SplashBitmap {",
        "    let width = u16::from_le_bytes([raw[0], raw[1]]);",
        "    let height = u16::from_le_bytes([raw[2], raw[3]]);",
        "    SplashBitmap {",
        "        width,",
        "        height,",
        "        pixels: raw.split_at(4).1,",
        "    }",
        "}",
        "",
    ]
    for name, img in entries:
        rel = f"../../fonts/splash/{name}.bin"
        lines.append(f"pub static {name.upper()}: SplashBitmap = parse(include_bytes!(\"{rel}\"));")
        lines.append("")
    with open(RS_PATH, "w") as f:
        f.write("\n".join(lines))


def make_preview(entries: list[tuple[str, Image.Image]]) -> None:
    # Dark nebula-like background, stacked like the splash.
    W, H = 960, 540
    bg = Image.new("RGB", (W, H), (12, 10, 32))
    px = bg.load()
    for y in range(H):
        t = y / H
        r = int(8 + t * 20)
        g = int(6 + t * 12)
        b = int(24 + t * 40)
        for x in range(W):
            px[x, y] = (r, g, b)

    def blit(img: Image.Image, y: int, color: tuple[int, int, int], shadow: bool = False) -> int:
        x = (W - img.width) // 2
        if shadow:
            blit_color(bg, img, x, y + 3, (6, 8, 22), 150)
        blit_color(bg, img, x, y, color, 255)
        return y + img.height

    y = H // 2 - 90
    by_name = {n: im for n, im in entries}
    y = blit(by_name["logo"], y, (236, 242, 255), shadow=True) + 22
    y = blit(by_name["tagline"], y, (156, 172, 208)) + 14
    y = blit(by_name["version"], y, (112, 128, 168)) + 20
    # fake bar
    bar_w, bar_h = 280, 4
    bx = (W - bar_w) // 2
    for dx in range(bar_w):
        for dy in range(bar_h):
            if dx < bar_w * 0.35:
                t = dx / bar_w
                px[bx + dx, y + dy] = (
                    int(60 + t * 40),
                    int(130 + t * 80),
                    int(220 + t * 35),
                )
            else:
                px[bx + dx, y + dy] = (40, 40, 60)
    y += bar_h + 14
    blit(by_name["status"], y, (132, 148, 188))
    bg.save(PREVIEW_PATH)
    print(f"Preview: {PREVIEW_PATH}")


def blit_color(
    dst: Image.Image,
    alpha: Image.Image,
    x: int,
    y: int,
    color: tuple[int, int, int],
    strength: int,
) -> None:
    dp = dst.load()
    ap = alpha.load()
    dw, dh = dst.size
    aw, ah = alpha.size
    cr, cg, cb = color
    for sy in range(ah):
        dy = y + sy
        if dy < 0 or dy >= dh:
            continue
        for sx in range(aw):
            dx = x + sx
            if dx < 0 or dx >= dw:
                continue
            a = ap[sx, sy] * strength // 255
            if a == 0:
                continue
            br, bg, bb = dp[dx, dy]
            inv = 255 - a
            dp[dx, dy] = (
                (cr * a + br * inv) // 255,
                (cg * a + bg * inv) // 255,
                (cb * a + bb * inv) // 255,
            )


def main() -> None:
    os.makedirs(OUT_DIR, exist_ok=True)
    entries: list[tuple[str, Image.Image]] = []
    for name, text, ttf, px, tracking in STRINGS:
        img = render_string_v2(ttf, text, px, tracking)
        write_bin(os.path.join(OUT_DIR, f"{name}.bin"), img)
        print(f"  {name}: {img.size[0]}x{img.size[1]} {text!r}")
        entries.append((name, img))
    write_rust(entries)
    make_preview(entries)
    print(f"Wrote {RS_PATH}")


if __name__ == "__main__":
    sys.path.insert(0, os.path.dirname(INTER_BOLD))
    main()
