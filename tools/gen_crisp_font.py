def make_compact(g16):
    """8x12: trim top 2 rows, bottom 2 rows from 8x16"""
    return g16[2:14]

def main():
    out_path = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                            '..', 'kernel', 'src', 'gui', 'hack_font.rs')

    lines = []
    lines.append('/// Hack Bitmap Font — pixel-perfect 1-bit glyphs for KnoxOS')
    lines.append('///')
    lines.append('/// Crisp, razor-sharp monospace rendering like macOS iTerm2.')
    lines.append('/// Each pixel is either fully ON or fully OFF — no antialiasing, no blur.')
    lines.append('/// This is the gold standard for terminal/UI text at native resolution.')
    lines.append('///')
    lines.append('/// Format: each glyph row is a single u8, MSB = leftmost pixel.')
    lines.append('/// Standard: 8x16, Compact: 8x12.')
    lines.append('')
    lines.append('/// Glyph width in pixels (both standard and compact)')
    lines.append('pub const GLYPH_WIDTH: usize = 8;')
    lines.append('/// Standard glyph height in pixels')
    lines.append('pub const GLYPH_HEIGHT: usize = 16;')
    lines.append('/// Compact glyph height in pixels')
    lines.append('pub const GLYPH_HEIGHT_COMPACT: usize = 12;')
    lines.append('')
    lines.append('const GLYPH_COUNT: usize = 95;')
    lines.append('')
    lines.append('/// Look up the standard 8x16 glyph for a character.')
    lines.append('/// Returns 16 row bytes (MSB = leftmost pixel).')
    lines.append('#[inline]')
    lines.append("pub fn get_glyph(ch: char) -> Option<&'static [u8; GLYPH_HEIGHT]> {")
    lines.append('    let idx = ch as usize;')
    lines.append('    if idx >= 0x20 && idx <= 0x7E {')
    lines.append('        Some(&HACK_STANDARD[idx - 0x20])')
    lines.append('    } else {')
    lines.append('        None')
    lines.append('    }')
    lines.append('}')
    lines.append('')
    lines.append('/// Look up the compact 8x12 glyph for a character.')
    lines.append('/// Returns 12 row bytes (MSB = leftmost pixel).')
    lines.append('#[inline]')
    lines.append("pub fn get_glyph_compact(ch: char) -> Option<&'static [u8; GLYPH_HEIGHT_COMPACT]> {")
    lines.append('    let idx = ch as usize;')
    lines.append('    if idx >= 0x20 && idx <= 0x7E {')
    lines.append('        Some(&HACK_COMPACT[idx - 0x20])')
    lines.append('    } else {')
    lines.append('        None')
    lines.append('    }')
    lines.append('}')
    lines.append('')

    # Standard 8x16
    lines.append('#[rustfmt::skip]')
    lines.append('static HACK_STANDARD: [[u8; GLYPH_HEIGHT]; GLYPH_COUNT] = [')
    for i, glyph in enumerate(HACK_8x16):
        code = 0x20 + i
        ch = chr(code)
        if ch == '\\':
            label = "0x{:02X} '\\\\'".format(code)
        elif ch == "'":
            label = "0x{:02X} '\\''".format(code)
        else:
            label = "0x{:02X} '{}'".format(code, ch)
        hex_str = ', '.join('0x{:02X}'.format(b) for b in glyph)
        lines.append('    // {}'.format(label))
        lines.append('    [{}],'.format(hex_str))
    lines.append('];')
    lines.append('')

    # Compact 8x12
    lines.append('#[rustfmt::skip]')
    lines.append('static HACK_COMPACT: [[u8; GLYPH_HEIGHT_COMPACT]; GLYPH_COUNT] = [')
    for i, glyph in enumerate(HACK_8x16):
        code = 0x20 + i
        compact = make_compact(glyph)
        ch = chr(code)
        if ch == '\\':
            label = "0x{:02X} '\\\\'".format(code)
        elif ch == "'":
            label = "0x{:02X} '\\''".format(code)
        else:
            label = "0x{:02X} '{}'".format(code, ch)
        hex_str = ', '.join('0x{:02X}'.format(b) for b in compact)
        lines.append('    // {}'.format(label))
        lines.append('    [{}],'.format(hex_str))
    lines.append('];')

    with open(out_path, 'w') as f:
        f.write('\n'.join(lines) + '\n')

    print("Written {} ({} bytes)".format(out_path, os.path.getsize(out_path)))
    print("Format: 1-bit pixel-perfect (8x16 standard, 8x12 compact)")
    print("Style: macOS iTerm2 crisp rendering - zero blur")

