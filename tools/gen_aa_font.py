def get_bit(byte_val, bit_pos):
    """Get bit at position (7=MSB, 0=LSB)."""
    return 1 if byte_val & (1 << (7 - bit_pos)) else 0


def bitmap_to_grid(bitmap, w, h):
    """Convert 1-bit packed bitmap to 2D boolean grid."""
    grid = []
    for row in range(h):
        r = []
        for col in range(w):
            r.append(get_bit(bitmap[row], col))
        grid.append(r)
    return grid


def rasterize_coverage(src_grid, src_w, src_h, dst_w, dst_h):
    """
    Compute exact area-coverage for each destination pixel.

    For each dst pixel, compute what fraction of its area overlaps
    source ON pixels. This IS the alpha — simple, correct, crisp.

    Interior pixels -> 1.0 (fully covered -> 255)
    Edge pixels    -> fractional (smooth AA transition)
    Background     -> 0.0 (transparent -> 0)
    """
    dst = [[0.0] * dst_w for _ in range(dst_h)]
    sx = src_w / dst_w   # source units per dest pixel
    sy = src_h / dst_h

    for dy in range(dst_h):
        src_y0 = dy * sy
        src_y1 = (dy + 1) * sy

        for dx in range(dst_w):
            src_x0 = dx * sx
            src_x1 = (dx + 1) * sx

            coverage = 0.0
            total_area = (src_x1 - src_x0) * (src_y1 - src_y0)

            iy0 = int(src_y0)
            iy1 = min(int(math.ceil(src_y1)), src_h)
            ix0 = int(src_x0)
            ix1 = min(int(math.ceil(src_x1)), src_w)

            for iy in range(iy0, iy1):
                ov_y = min(iy + 1.0, src_y1) - max(float(iy), src_y0)
                if ov_y <= 0:
                    continue
                for ix in range(ix0, ix1):
                    if src_grid[iy][ix] == 0:
                        continue
                    ov_x = min(ix + 1.0, src_x1) - max(float(ix), src_x0)
                    if ov_x <= 0:
                        continue
                    coverage += ov_x * ov_y

            if total_area > 0:
                dst[dy][dx] = coverage / total_area

    return dst


def coverage_to_alpha(cov_grid, dst_w, dst_h):
    """
    Convert coverage [0..1] to uint8 alpha [0..255].

    - >= 0.99 -> 255 (solid interior, no half-opacity nonsense)
    - <= 0.01 -> 0   (clean background)
    - Edge: slight boost (gamma ~0.8) so thin strokes stay visible
    """
    result = [[0] * dst_w for _ in range(dst_h)]
    for dy in range(dst_h):
        for dx in range(dst_w):
            c = cov_grid[dy][dx]
            if c >= 0.99:
                result[dy][dx] = 255
            elif c <= 0.01:
                result[dy][dx] = 0
            else:
                boosted = math.pow(c, 0.8)
                alpha = int(boosted * 255.0 + 0.5)
                result[dy][dx] = max(1, min(254, alpha))
    return result


