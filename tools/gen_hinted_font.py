def make_compact(g16):
    """8x12: rows 2..14 of the 8x16 glyph (trim 2 top, 2 bottom)."""
    return g16[2:14]


def main():
    out_path = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                            '..', 'kernel', 'src', 'gui', 'hack_font.rs')

    lines = []
    lines.append('/// KnoxOS Pixel-Perfect Font — hand-hinted 8×16 monospace glyphs')
    lines.append('///')
    lines.append('/// Every glyph is hand-crafted for maximum clarity at native resolution:')
    lines.append('///   - Symmetric strokes with consistent 1-2px weight')
    lines.append('///   - Balanced curves (centered arcs, no jagged edges)')
    lines.append('///   - Even spacing (centered in cell, consistent sidebearings)')
    lines.append('///   - Distinct confusable chars: 0/O (slashed zero), 1/l/I, etc.')
    lines.append('///   - Clean diagonals with minimal stairstepping')
    lines.append('///')
    lines.append('/// Like SVG at pixel resolution — every pixel is in exactly the right place.')
    lines.append('/// Format: each row is u8, MSB = leftmost pixel. Standard 8×16, Compact 8×12.')
    lines.append('')
    lines.append('/// Glyph width in pixels')
    lines.append('pub const GLYPH_WIDTH: usize = 8;')
    lines.append('/// Standard glyph height in pixels')
    lines.append('pub const GLYPH_HEIGHT: usize = 16;')
    lines.append('/// Compact glyph height in pixels')
    lines.append('pub const GLYPH_HEIGHT_COMPACT: usize = 12;')
    lines.append('')
    lines.append('const GLYPH_COUNT: usize = 95;')
    lines.append('')
    lines.append('/// Look up the standard 8×16 glyph for a character.')
    lines.append('#[inline]')
    lines.append("pub fn get_glyph(ch: char) -> Option<&'static [u8; GLYPH_HEIGHT]> {")
    lines.append('    let idx = ch as usize;')
    lines.append('    if idx >= 0x20 && idx <= 0x7E {')
    lines.append('        Some(&HACK_STANDARD[idx - 0x20])')
    lines.append('    } else {')
    lines.append('        None')
    lines.append('    }')
    lines.append('}')
    lines.append('')
    lines.append('/// Look up the compact 8×12 glyph for a character.')
    lines.append('#[inline]')
    lines.append("pub fn get_glyph_compact(ch: char) -> Option<&'static [u8; GLYPH_HEIGHT_COMPACT]> {")
    lines.append('    let idx = ch as usize;')
    lines.append('    if idx >= 0x20 && idx <= 0x7E {')
    lines.append('        Some(&HACK_COMPACT[idx - 0x20])')
    lines.append('    } else {')
    lines.append('        None')
    lines.append('    }')
    lines.append('}')
    lines.append('')

    # Standard 8x16
    lines.append('#[rustfmt::skip]')
    lines.append('static HACK_STANDARD: [[u8; GLYPH_HEIGHT]; GLYPH_COUNT] = [')
    for i, g in enumerate(GLYPHS):
        code = 0x20 + i
        ch = chr(code)
        if ch == '\\': label = "0x{:02X} '\\\\'".format(code)
        elif ch == "'": label = "0x{:02X} '\\''".format(code)
        else: label = "0x{:02X} '{}'".format(code, ch)
        hex_str = ', '.join('0x{:02X}'.format(b) for b in g)
        lines.append('    // {}'.format(label))
        lines.append('    [{}],'.format(hex_str))
    lines.append('];')
    lines.append('')

    # Compact 8x12
    lines.append('#[rustfmt::skip]')
    lines.append('static HACK_COMPACT: [[u8; GLYPH_HEIGHT_COMPACT]; GLYPH_COUNT] = [')
    for i, g in enumerate(GLYPHS):
        code = 0x20 + i
        compact = make_compact(g)
        ch = chr(code)
        if ch == '\\': label = "0x{:02X} '\\\\'".format(code)
        elif ch == "'": label = "0x{:02X} '\\''".format(code)
        else: label = "0x{:02X} '{}'".format(code, ch)
        hex_str = ', '.join('0x{:02X}'.format(b) for b in compact)
        lines.append('    // {}'.format(label))
        lines.append('    [{}],'.format(hex_str))
    lines.append('];')

    with open(out_path, 'w') as f:
        f.write('\n'.join(lines) + '\n')

    sz = os.path.getsize(out_path)
    print("Written {} ({} bytes)".format(out_path, sz))

    # Visual verification
    print("\nSample glyphs:")
    for ch_code in [0x41, 0x42, 0x43, 0x48, 0x4F, 0x30, 0x61, 0x65, 0x69, 0x6F]:
        g = GLYPHS[ch_code - 0x20]
        print("  {} (0x{:02X}):".format(chr(ch_code), ch_code))
        for row in g:
            line = ''
            for b in range(8):
                line += '██' if row & (0x80 >> b) else '  '
            print("    {}".format(line))

if __name__ == "__main__":
    main()
