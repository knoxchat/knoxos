# ─────────────────────────────────────────────────────────
# Hand-hinted 8×16 glyphs — SF Mono / Menlo quality
# Each row: MSB=leftmost pixel, 8 bits wide, 16 rows tall
# Design grid:  col 76543210
#               row 0..15
# ─────────────────────────────────────────────────────────

def B(s):
    """Convert visual binary string to byte. '.' = 0, '#' = 1."""
    val = 0
    for i, c in enumerate(s):
        if c == '#':
            val |= (0x80 >> i)
    return val

def glyph(rows_str):
    """Parse 16-line visual glyph definition."""
    lines = [l.strip() for l in rows_str.strip().split('\n')]
    assert len(lines) == 16, f"Expected 16 rows, got {len(lines)}"
    return [B(l) for l in lines]

