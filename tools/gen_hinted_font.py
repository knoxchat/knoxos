"""
Generate hand-hinted pixel-perfect font for KnoxOS.

Every glyph is hand-crafted at 8x16 for maximum clarity:
- Symmetric strokes (consistent 1-2px weight)
- Balanced curves (mathematically centered arcs)
- Even spacing (centered in cell with consistent sidebearings)
- Clean diagonals (no jagged stairstepping)
- Distinct similar chars (0/O, 1/l/I, etc.)

Think of it as an SVG font rasterized to the perfect grid — each pixel
is in exactly the right place. No filtering needed because the source
data IS the target resolution.
"""
